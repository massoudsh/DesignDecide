#!/usr/bin/env bash
# Create the deployment .env for docker compose with a generated,
# URL-safe PostgreSQL password. The file is gitignored and mode 600.
set -euo pipefail

root_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
env_file="$root_dir/.env"
# shellcheck source=scripts/env-lib.sh
. "$root_dir/scripts/env-lib.sh"
force=0

for arg in "$@"; do
  case "$arg" in
    --force) force=1 ;;
    -h|--help)
      printf 'Usage: %s [--force]\n\nCreates .env with POSTGRES_PASSWORD and DATABASE_URL.\nRefuses to overwrite an existing .env unless --force is passed.\n' "$0"
      exit 0
      ;;
    *)
      printf 'Unknown option: %s\n' "$arg" >&2
      exit 2
      ;;
  esac
done

if [ ! -f "$root_dir/compose.yaml" ]; then
  printf 'compose.yaml not found next to %s\n' "$root_dir" >&2
  exit 1
fi

if [ -e "$env_file" ] && [ "$force" -ne 1 ]; then
  printf 'Refusing to overwrite existing %s. Re-run with --force to replace it.\n' "$env_file" >&2
  exit 1
fi

# A stale shell value would silently override the .env Compose reads.
for key in POSTGRES_PASSWORD DATABASE_URL; do
  if [ -n "${!key-}" ]; then
    printf '%s is set in the current shell and overrides .env for docker compose.\n' "$key" >&2
    printf 'Run: unset %s   (then re-run this script)\n' "$key" >&2
    exit 1
  fi
done

if command -v openssl >/dev/null 2>&1; then
  password="$(openssl rand -hex 24)"
else
  password="$(head -c 32 /dev/urandom | base64 | LC_ALL=C tr -dc 'A-Za-z0-9' | cut -c1-48)"
fi

case "$password" in
  ""|*[!A-Za-z0-9]*)
    printf 'Failed to generate a URL-safe password.\n' >&2
    exit 1
    ;;
esac

umask 077
{
  printf '# Generated by scripts/setup-env.sh. Do not commit this file.\n'
  printf 'POSTGRES_PASSWORD=%s\n' "$password"
  printf 'DATABASE_URL=postgresql://tarhyar:%s@db:5432/tarhyar?schema=public\n' "$password"
  printf '# Optional: change the loopback port the app is published on.\n'
  printf '# WEB_PORT=3000\n'
} > "$env_file"
chmod 600 "$env_file"

printf 'Wrote %s with a generated PostgreSQL password (mode 600).\n' "$env_file"
printf 'Next: docker compose up -d --build\n'
